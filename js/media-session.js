/*
======================================================================
 media-session.js ── ロック画面・バックグラウンド再生の連携

----------------------------------------------------------------------

【このファイルを作った理由(竹弘の報告、2026-08-22)】

 「スマホの電源ボタンを1回押して画面ロック(時計やカレンダーが
 出る節電状態)にすると、曲が2曲ほど鳴った後に止まる」

 このアプリはブラウザで動くWebアプリ(PWA)です。ネイティブの音楽
 アプリと違い、ブラウザは「今このタブは本当に音楽を再生し続けたい
 アプリなのか」をOS(Android)へ自分で伝える必要があります。それを
 伝える標準の仕組みが Media Session API です。

 これを何も使っていないと、Androidは画面ロック中のタブを「もう
 使われていない」とみなし、電池を守るためにJavaScriptの動きを
 止めてしまうことがあります。これが「2曲目までは鳴るが、その先の
 “次の曲へ進む”判断(js/queue.js)が動けなくなって止まる」という
 症状の正体だと考えられます。

----------------------------------------------------------------------

【画面ロック中も音を止めない、が目的(Wake Lockとの違い)】

 竹弘の狙いは「画面を触らない=節電のために画面を消す」ことであって、
 「画面を点けっぱなしにする」ことではありません。そのため、画面を
 強制的に点灯させ続ける Wake Lock API はここでは使いません。
 画面は消えたままでよく、その状態でもOSに「音楽再生アプリとして
 現在進行中です」と伝え続けるのがこの機能の役目です。

 副産物として、ロック画面や通知欄・イヤホンのボタンから再生/一時
 停止・前後の曲送りができるようにもなります(未着手だった
 「ロック画面/イヤホン操作」の下地です)。

----------------------------------------------------------------------

【対応していないブラウザでは何もしない】

 Media Session API はAndroidのChromeでは使えますが、対応していない
 ブラウザも存在します。"mediaSession" in navigator で対応状況を
 確かめ、対応していなければ何もせず終わります(このアプリの他の
 機能には影響しません)。
======================================================================
*/


// このAPIに対応していないブラウザでは、以下は何もしません
const mediaSessionSupported = ("mediaSession" in navigator);


// ==========================================================
// 1. 曲情報(タイトル・アーティスト・ジャケット)を伝える
// ==========================================================

// 前の曲のジャケット用に作った一時URLを覚えておきます(後始末のため)
let mediaSessionArtworkUrl = null;

/**
 * 今再生している曲の情報を、Media Sessionに登録します。
 *
 * js/player.js の playTrack() が、曲を鳴らし始めるたびに呼びます。
 *
 * @param {Object} track … libraryMap から取り出した1曲分のデータ
 */
function updateMediaSessionMetadata(track){

    if(!mediaSessionSupported){ return; }
    if(!track){ return; }

    /*
    前の曲で作ったジャケット用の一時URLを解放します。

    deck.js の deckObjectUrls(曲そのものの再生用URLの台帳)と
    同じ考え方です。解放し忘れると、曲を切り替えるたびに
    ブラウザがメモリを確保し続けてしまいます。
    (v168まではこの説明で player.js の currentObjectUrl を
     指していましたが、その変数はデッキごとの台帳へ移りました)
    */
    if(mediaSessionArtworkUrl){
        URL.revokeObjectURL(mediaSessionArtworkUrl);
        mediaSessionArtworkUrl = null;
    }

    const artwork = [];

    /*
    どの画像を出すかは getTrackCover()(js/list-view.js)が決めます。
    差し替え(📷で作ったジャケット)があればそちら、無ければ
    音楽ファイルに埋め込まれていた元のジャケットです。

    ⚠️ **ロック画面もここに合わせます。** 曲一覧・上半分・特大表示だけ
       差し替わって、ロック画面だけ元の絵のまま…という食い違いが
       起きないように、4か所すべてが同じ関数を見る形にしています(v207)。
    */
    const cover = getTrackCover(track);

    if(cover){

        mediaSessionArtworkUrl = URL.createObjectURL(cover);

        /*
        cover_art は docs/db-schema.md の通り、一辺 COVER_ART_SIZE px の
        正方形へ縮小済みのJPEGです。sizes にその実際の値を伝えます。

        ⚠️ **数値を書き写さず、js/metadata.js の定数から組み立てます。**
           v205まではここに "96x96" と直接書いてあり、v206で保存解像度を
           96→480pxに上げた時に**ここだけ古い値が残ってロック画面に
           嘘のサイズを伝える**ところでした(CLAUDE.mdの「同じ数値を
           2か所に書かない」の実例)。定数を見に行く形なら、次に解像度を
           変えてもここは自動で追従します。

        sizes は「この画像は何ドット四方か」をOSに伝えるものです。
        Androidのロック画面は複数の候補から適した大きさを選ぶ作りなので、
        ここが実物と食い違うと、選ばれなかったり粗く表示されたりします。

        ⚠️ 読み込み順の補足:c014.html では js/metadata.js が
           このファイルより**後ろ**に並んでいます。それでも大丈夫なのは、
           この行が動くのは**曲が鳴り始めた時**で、その頃には全部の
           <script> が読み終わっているからです(読み込んだ瞬間に
           使うのであれば順番を気にする必要があります)。
        */
        const coverSizeText = COVER_ART_SIZE + "x" + COVER_ART_SIZE;

        artwork.push({
            src: mediaSessionArtworkUrl,
            sizes: coverSizeText,
            type: "image/jpeg"
        });

    }

    /*
    buildTitleText() は js/list-view.js にある「タイトルが無ければ
    ファイル名を使う」関数です。曲一覧・上半分(showNowPlaying)と
    同じ表示ルールを、ロック画面の表示にもそのまま使います。
    */
    navigator.mediaSession.metadata = new MediaMetadata({
        title: buildTitleText(track),
        artist: track.artist || "",
        artwork: artwork
    });

}


// ==========================================================
// 2. 再生/一時停止の状態を伝える
// ==========================================================
/*
audioの play/pause は、js/upper-area.js が停止ボタン(■/▶)の
記号を切り替えるのに使っているのと同じ標準イベントです。

「JSは今どうなっているかを写すだけ」というこのアプリの方針どおり、
ここでも実際の再生状態をそのままMedia Sessionへ伝えるだけにします。
*/
if(mediaSessionSupported){

    // v167: 2枚のデッキに対応(理由は js/deck.js のコメント)
    bindDeckEvent("play",function(){
        navigator.mediaSession.playbackState = "playing";
    });

    bindDeckEvent("pause",function(){
        navigator.mediaSession.playbackState = "paused";
    });

}


// ==========================================================
// 3. ロック画面・イヤホンからの操作を受け付ける
// ==========================================================
/*
setActionHandler は「ロック画面のこのボタンが押されたら、この関数を
呼んでください」とOSへ伝える命令です。

再生/一時停止は既存の停止ボタン(js/upper-area.js)と同じ操作を、
前後の曲送りは既存の⏮⏭ボタン(js/queue.js の skipTrack)と
同じ操作を呼ぶだけにしています。ボタンを増やすたびに操作の中身を
別々に書かず、すでにある入口を再利用することで、両方の操作方法で
挙動が食い違うことを防いでいます。

イヤホンのボタンがどの操作に化けるかは端末とイヤホンの組み合わせ
次第なので、実機での確認が必要です(竹弘への申し送り事項)。
*/
if(mediaSessionSupported){

    navigator.mediaSession.setActionHandler("play",function(){

        // 【開発用調査ログ】(v237)届いた操作を🐛パネルに残す(このファイルの最後の logMediaSessionAction)
        logMediaSessionAction("▶");

        audioPlayer.play();
    });

    navigator.mediaSession.setActionHandler("pause",function(){

        /*
        【開発用調査ログ】(v237)届いた操作を🐛パネルに残します
        (このファイルの最後の logMediaSessionAction)。

        ⚠️ 止める処理より**前**に置きます。残したいのは「届いた瞬間に、曲が
           鳴っていたか止まっていたか」で、止めた後に書くと必ず「止まっている」
           になってしまうためです。
        */
        logMediaSessionAction("⏸");

        /*
        意図した停止であることを js/upper-area.js の停止ボタン記号
        表示(v135)へ伝えます。ロック画面からの一時停止も、竹弘が
        自分で選んだ操作なので「意図した停止」として扱います。
        */
        intentionalPause = true;

        /*
        【v236】主役を止める**前に**、裏で鳴っている曲を止めて、繋ぐ準備を
        取りやめます(js/connect.js の prepareUserPause)。

        竹弘の実機(2026-10-12、テスト8):助走中に ⏸ で止めると、イヤホンの ▶ で
        一時停止を解除できなかった / クロスフェード中に止めると、先行曲が
        聞こえ続けた。2曲が同時に鳴っている時に主役を先に止めると、Chrome が
        イヤホン・通知の操作の相手を手放してしまうためです(詳しくは
        prepareUserPause のコメント)。■ボタンも同じ止め方です。
        */
        prepareUserPause();

        audioPlayer.pause();

    });

    navigator.mediaSession.setActionHandler("previoustrack",function(){

        // 【開発用調査ログ】(v237)届いた操作を🐛パネルに残す(このファイルの最後の logMediaSessionAction)
        logMediaSessionAction("⏮");

        skipTrack(-1);
    });

    navigator.mediaSession.setActionHandler("nexttrack",function(){

        // 【開発用調査ログ】(v237)届いた操作を🐛パネルに残す(このファイルの最後の logMediaSessionAction)
        logMediaSessionAction("⏭");

        skipTrack(1);
    });

}


// ==========================================================
// 4. 【開発用調査ログ】届いた操作を🐛パネルに残す(v237)
// ==========================================================
/**
 * イヤホン・通知・ロック画面から届いた操作を、🐛パネルに1行残します(v237)。
 *
 * ------------------------------------------------------------
 * 【なぜ作ったのか(竹弘の報告、2026-10-17)】
 *
 *     「イヤホンタッチで一時停止した後、1回目のタッチでは一時停止解除に
 *       ならない。必ずもう一度タッチすると解除になる。ネイティブアプリでは
 *       そんなことはない。ロック画面のオンオフは関係なかった」
 *
 * v236 までの上の受け口は、届いた操作を何もログに出していませんでした。
 * しかも止まっている時に ⏸ が届いても、止めるものが無いので何も起きません。
 * つまり**1回目のタッチで何が起きたのか、跡がどこにも残りません**でした。
 *
 * のりの見立て(未確認):イヤホン(またはスマホ)が、止めた後もノリRunを
 * 「鳴っている」と思っていて、1回目を ⏸ として送っている。すでに止まって
 * いるので何も起きず、2回目でやっと ▶ になる。
 * (ノリRunは一時停止中も、音の通り道(Web Audio)の出口を開けたまま無音を
 *  流しています。止めると出口ごと閉じるネイティブアプリとは、外から見た
 *  様子が違う可能性があります)
 * もう1つの可能性:1回目がこのアプリまで届いていない。
 *
 * この1行があれば、どちらなのかがはっきりします。
 *
 *     1回目が「⏸ が届いた … ★止まっている時の ⏸」と出る → 見立てどおり
 *     1回目では何も出ない                                → 届いていない
 *
 * ------------------------------------------------------------
 * 【何を書くか】
 *
 *     届いた操作     … ▶ ⏸ ⏭ ⏮
 *     主役 / 裏      … 2枚のデッキが、届いた瞬間に鳴っていたか止まっていたか
 *     伝えてある状態 … このアプリがChromeに伝えている再生状態
 *                      (navigator.mediaSession.playbackState。上の「2.」で
 *                       主役が鳴った・止まった時に書き換えている値)
 *     画面           … visible(見えている)/ hidden(消えている・裏にいる)
 *
 * ⚠️ イヤホンからか、通知・ロック画面のボタンからかは、ここでは見分け
 *    られません(どちらも同じ形で届くため)。竹弘が何を押したかと
 *    突き合わせて読みます。
 *
 * ------------------------------------------------------------
 * 【消す時(原因が分かって直したら)】
 *
 * この関数と、上の4つの受け口にある呼び出し行(「【開発用調査ログ】(v237)」の
 * 印付き)を消すだけです。動きには何も影響しません(CLAUDE.md の
 * 「本番リリース前に削除するもの」に登録済み)。
 *
 * ⚠️ js/debug-log.js(logDebugEvent の持ち主)を先に消しても壊れないよう、
 *    logDebugEvent が無ければ何もしない形にしてあります。ここでエラーに
 *    なると、その後ろの「止める」「鳴らす」が動かず、**イヤホンの操作
 *    そのものが効かなくなる**ためです。
 *
 * @param {string} label - 届いた操作の記号(▶ ⏸ ⏭ ⏮)
 */
function logMediaSessionAction(label){

    /*
    typeof は「その名前の物が何なのか」を文字で返します。まだ無い(読み込まれて
    いない・消された)名前でもエラーにならず "undefined" が返るので、
    「関数があれば使う」という確かめ方に使えます。
    */
    if(typeof logDebugEvent !== "function"){ return; }

    const mainPaused = audioPlayer.paused;

    // getIdleDeck() は js/deck.js にある「いま主役でない方のデッキ」です
    const idleDeck   = getIdleDeck();
    const idlePaused = !idleDeck || idleDeck.paused;

    /*
    ---- 食い違いの印 ----

    止まっている時に ⏸ が届く(鳴っている時に ▶ が届く)のは、送ってきた側が
    「いまの状態」を取り違えている印です。🐛パネルで見つけやすいように★を付けます。

    ⚠️ 裏のデッキが鳴っている時(助走中・🎬の無音の待ち・クロスフェードの後の
       完走中)は、Chrome から見ると「鳴っている」ので、⏸ が届くのは正しい
       動きです。その時は印を付けません。
    */
    let mark = "";

    if(label === "⏸" && mainPaused && idlePaused){
        mark = " ★止まっている時の ⏸(このままでは何も起きません)";
    }
    else if(label === "▶" && !mainPaused){
        mark = " ★鳴っている時の ▶";
    }

    logDebugEvent(
        "イヤホン・通知の操作 : " + label + " が届いた" +
        " / 主役 = " + (mainPaused ? "止まっている" : "鳴っている") +
        "・裏 = " + (idlePaused ? "止まっている" : "鳴っている") +
        " / 伝えてある状態 = " + navigator.mediaSession.playbackState +
        " / 画面 = " + document.visibilityState +
        mark
    );

}
