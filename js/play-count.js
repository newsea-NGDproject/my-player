/*
======================================================================
 play-count.js ── 再生回数の記録

----------------------------------------------------------------------

【このファイルの役割】

 曲が実際に鳴り始めるたびに、その曲の再生回数を1増やして
 music_library に保存します。竹弘の希望で、並び替えメニューの
 「🔥再生回数順」で使うためのフィールドです。

   incrementPlayCount() … 再生回数を1増やす

----------------------------------------------------------------------

【いつ呼ばれるか】

 「曲が鳴り始めた」と言える瞬間は2か所あります。

   ・js/player.js の playTrack() … 曲一覧タップ・連続再生・曲送りなど、
     ほとんどの再生はここを通ります
   ・js/queue.js の 1曲リピート成功時 … 同じ曲を頭から鳴らし直す軽い
     再生で、playTrack() を経由しないため別途呼ぶ必要があります

 1曲リピートで同じ曲を10回繰り返せば、再生回数も10増えます。
 「聴いた回数」としては素直な数え方です。

----------------------------------------------------------------------

【桁数について】

 竹弘の確認: 「回数は一般的なツールは10桁という話しを聞きました。
 10桁で問題ありません」

 JavaScriptの数値(Number)は、10桁程度の整数であれば誤差なく
 正確に扱えます(安全に扱える上限は2の53乗、16桁近くまで)。
 特別な型やライブラリは不要です。
======================================================================
*/


/**
 * 指定した曲の再生回数を1増やして保存します。
 *
 * @param {string} trackId - 再生回数を増やす曲
 */
async function incrementPlayCount(trackId){

    const track = libraryMap[trackId];

    if(!track){ return; }

    // 保存に失敗した時、メモリ上の値を元に戻すため覚えておきます
    const previousValue = track.play_count || 0;

    track.play_count = previousValue + 1;

    try{

        await idbPut(STORE_MUSIC,track);

    }
    catch(error){

        /*
        保存に失敗した場合は、メモリ上の値も元に戻します。
        戻さないと「画面ではカウントが増えているのに、次に開くと
        元に戻っている」という分かりにくい食い違いが起きるためです
        (nori.js・favorite.js と同じ考え方)。
        */
        track.play_count = previousValue;

        console.error(
            "再生回数の保存に失敗 :",
            track.file_name,
            error.name,
            error.message
        );

    }

}
