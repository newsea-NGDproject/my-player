/*
======================================================================
 config.js ── アプリ全体で共有する「定数」と「状態」

----------------------------------------------------------------------

【このファイルの役割】

 c014(メインメニュー)を構成する複数のJSファイルが、共通して使う
 ものだけをここに集めています。

   ① 定数     … DBの名前やストア名など、書き換えない決まった値
   ② 画面部品 … HTMLの要素をJSから触るための入り口
   ③ 共有状態 … 「今の曲順」「曲データの早見表」など、
                 複数のファイルが読み書きする変数

----------------------------------------------------------------------

【なぜファイルを分けたのか】

 c014.htmlは1ファイルで約3,000行まで育ちました。この先ビート
 マッチング(音声処理)を足すと手に負えなくなるため、機能ごとに
 JSファイルを分け、「今どこを触っているか」がはっきり分かる形に
 しています。

 分割の効果はもう一つあります。竹弘はGitHubへ手動でファイルを
 アップロードしているため、1文字直すたびに100KB超のc014.htmlを
 丸ごと上げ直す必要がありました。分割後は「直したファイルだけ」で
 済みます。

----------------------------------------------------------------------

【読み込みの順番が大事】

 これらのファイルは c014.html の一番下で、次の順番で読み込まれます。

   config → db → list-view → player → drag-sort
          → lamp → metadata → main

 このファイルが先頭なのは、他の全ファイルがここの値を使うためです。
 特に「画面部品」はHTMLが組み上がった後でないと取得できないので、
 <script>タグは必ず </body> の直前に置きます。

----------------------------------------------------------------------

【なぜ import / export を使わないのか】

 JavaScriptには ES Modules(import / export)という、ファイルを
 分けるための新しい仕組みがあります。しかし今回はあえて使わず、
 昔ながらの <script> タグを順番に並べる方式にしています。

 理由は「分割で動作を変えないため」です。

 ES Modulesにすると、各ファイルが独立した部屋のように区切られ、
 変数の見え方(スコープ)が今までと変わります。特に困るのが
 currentOrderList や libraryMap のように
 「複数のファイルから中身を入れ替える変数」で、
 ES Modulesでは import した変数への代入が禁止されているため、
 状態の持ち方そのものを作り直す必要が出てきます。

 それは、動くコードを大きく書き換えるということ。
 過去2回の開発が「機能追加のたびに完成済み機能が壊れる」で
 崩壊した経緯を踏まえ、今回の分割は
 「置き場所を変えるだけで、コードは1文字も書き換えない」
 引っ越し作業に徹しました。

 <script>を並べる方式なら、全ファイルが今まで通り同じ1つの
 空間を共有するので、変数の見え方はc014.html1枚だった頃と
 完全に同じままです。
======================================================================
*/


