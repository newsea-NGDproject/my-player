/*
======================================================================
 nori.js ── ノリ注入ボタン

----------------------------------------------------------------------

【このファイルの役割】

 曲一覧の一番左にあるボタンです。ノリRunというアプリの
 一番の売りになる部分を担当します。

   🛌 … まだノリが入っていない曲(寝ている)
   🕺 … ノリが注入された曲(踊っている)

 legacy(ver8.5-gemini)の OFS Ver.1.0 から移植しました。
 記号も判定に使うフィールドも、legacyと同じものを使っています。

----------------------------------------------------------------------

【「ノリ注入」とは何か】

 竹弘の構想では、これから作る「タップ補正ツール」で曲のリズムを
 解析し、走るテンポに合わせられる状態にすることを指します。
 ノリが注入された曲だけが、ビートマッチングで気持ちよく繋がります。

 そのツールはまだ無いため、今の段階ではボタンを押すと
 「注入済みの印」を付けるところまでを行います。
 見た目の切り替えと、その状態がDBに残ることを先に用意しておく形です。

 タップ補正ツールができたら、このファイルの injectNori() から
 その画面を呼び出すことになります。

----------------------------------------------------------------------

【一方通行にしている理由】

 一度🕺にした曲を🛌へ戻すことはできません。legacy の OFS と
 同じ振る舞いで、竹弘の指示によるものです。

 将来、本物のタップ補正ツールができれば、🕺は「補正データを
 持っている曲」を意味することになります。ボタンを押すだけで
 その印を取り消せてしまうと、実際のデータと表示がずれるため、
 最初から戻せない作りにしています。

----------------------------------------------------------------------

【is_analyzed というフィールドについて】

 曲がノリ注入済みかどうかは、music_library の is_analyzed に
 記録します(docs/db-schema.md 参照)。c013の頃から用意されて
 いたフィールドで、今回ようやく使われることになりました。

 名前が似ているフィールドが他に2つあるので、混同しないこと。

   is_analyzed       … ノリ注入済みか(このファイルの担当)
   is_meta_analyzed  … タイトル等のタグを読んだか(metadata.jsの担当)
   is_cover_analyzed … ジャケット画像を調べたか(metadata.jsの担当)
======================================================================
*/


// ==========================================================
// 1. ボタンに出す記号
// ==========================================================
/*
legacy の OFS Ver.1.0 で使われていた記号をそのまま使います。

    🛌 (U+1F6CC) … 寝ている人
    🕺 (U+1F57A) … 踊っている人

数値を直接書かず定数にしているのは、後で記号を変えたく
なった時に、ここ1箇所を直すだけで済むようにするためです。
*/
const NORI_ICON_SLEEPING = "🛌";
const NORI_ICON_DANCING = "🕺";


/**
 * その曲に出すべき記号を返します。
 *
 * 曲一覧の行を作る時(list-view.js)から呼ばれます。
 */
function buildNoriIcon(track){

    return track.is_analyzed ? NORI_ICON_DANCING : NORI_ICON_SLEEPING;

}


// ==========================================================
// 2. ノリを注入する
// ==========================================================
/**
 * ノリ注入ボタンが押された時の処理です。
 *
 * @param {string} trackId       - 対象の曲
 * @param {Element} buttonElement - 押されたボタン本体(表示を変えるため)
 *
 * 【なぜボタンそのものを受け取るのか】
 *
 * 行を丸ごと作り直せば表示は更新できますが、それだと押した瞬間に
 * 行が消えて作り直されるため、指の下で画面がちらつきます。
 * 押されたボタンの文字だけを書き換える方が、動きが自然です。
 * legacy の OFS も同じやり方をしていました。
 */
async function injectNori(trackId,buttonElement){

    const track = libraryMap[trackId];

    if(!track){ return; }

    /*
    すでに注入済みの曲は何もしません(一方通行のため)。

    タップ補正ツールができたら、ここが
    「その曲の補正画面を開く」入口になります。
    */
    if(track.is_analyzed){

        console.log("この曲はすでにノリ注入済みです :",track.file_name);

        return;

    }

    try{

        track.is_analyzed = true;

        /*
        ノリを注入した日時を記録します(v79で追加)。

        【何に使うのか】
        これから作る並び替え機能で、「最近ノリを注入した曲から順に
        上へ持ってくる」ために使います。走る前に、さっき仕込んだ曲を
        すぐ見つけられるようにするためです(竹弘の構想)。

        【なぜ並び替え機能より先に入れたのか】
        後から足すと、それまでに注入した曲には日時が残っておらず、
        「いつ注入したか分からない曲」ができてしまいます。
        記録だけ先に始めておけば、その取りこぼしが起きません。

        Date.now() は1970年1月1日からの経過ミリ秒を返す標準の命令です。
        数値なので大小を比べるだけで新しい順に並べられます。
        */
        track.nori_injected_at = Date.now();

        await idbPut(STORE_MUSIC,track);

        // 保存が成功してから表示を変えます
        buttonElement.textContent = NORI_ICON_DANCING;

        /*
        日時も一緒にログへ出しています。画面には出ない情報なので、
        これが無いと「本当に記録できているか」を竹弘が実機で
        確かめられないためです。

        toLocaleString() は、ミリ秒の数値を
        「2026/8/14 10:23:45」のような読める形に直す標準の命令です。
        */
        console.log(
            "ノリを注入しました :",
            track.file_name,
            "/ 注入日時 :",
            new Date(track.nori_injected_at).toLocaleString()
        );

    }
    catch(error){

        /*
        保存に失敗した場合は、メモリ上の値も元に戻します。

        戻さないでいると「画面ではノリ注入済みなのに、
        次に開くと元に戻っている」という分かりにくい食い違いが
        起きるためです。
        */
        track.is_analyzed = false;
        track.nori_injected_at = undefined;

        console.error(
            "ノリ注入の保存に失敗 :",
            track.file_name,
            error.name,
            error.message
        );

    }

}
